import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve('outputs/Projet9');
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8501');
await page.getByText('Exemple fourni',{exact:true}).click();
const combo=page.getByRole('combobox');await combo.click();
await page.getByRole('option',{name:'route_readable.jpg',exact:true}).click();
await page.getByRole('button',{name:'Analyser',exact:true}).click();
await page.getByRole('button',{name:'Télécharger les résultats JSON'}).waitFor({timeout:120000});
await page.screenshot({path:path.join(root,'results/app_screenshot.png'),fullPage:false});
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Télécharger les résultats JSON'}).click();
const download=await downloadPromise;
await download.saveAs(path.join(root,'results/browser_download.json'));
const result=JSON.parse(await fs.readFile(path.join(root,'results/browser_download.json'),'utf8'));
await page.getByRole('button',{name:'Télécharger les résultats JSON'}).waitFor();
await page.getByText('Détections du système',{exact:true}).waitFor();
await page.getByText('Importer une image',{exact:true}).click();
await page.locator('input[type=file]').setInputFiles({name:'invalid.jpg',mimeType:'image/jpeg',buffer:Buffer.from('not an image')});
await page.getByText('Impossible de lire cette image.',{exact:true}).waitFor();
const evidence={url:page.url(),title:await page.title(),errors,download_valid:Array.isArray(result.detections),download_bytes:(await fs.stat(path.join(root,'results/browser_download.json'))).size,results_persist_after_download:true,invalid_image_handled:true};
await fs.writeFile(path.join(root,'results/browser_test.json'),JSON.stringify(evidence,null,2));
await browser.close();
if(errors.length||!evidence.download_valid)throw new Error(JSON.stringify(evidence));
console.log(JSON.stringify(evidence));
